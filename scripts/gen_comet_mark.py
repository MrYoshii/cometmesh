"""Generate the Comet boot mark: one geometry, two outputs.

- src/ui-touch/CometMarkGeom.h: the strands of the tails and the head, which the
  LVGL boot splash draws and animates (UITask.cpp, splashMarkDrawCb).
- src/comet_mark_rgb.h: the same comet as an anti-aliased white-on-black RGB565
  bitmap (208 x 110), painted by the pre-LVGL boot screen and the static screens,
  so the hand-off to the animated splash does not jump.

The comet flies to the right: the head sits right of centre, the tails stream to
the left and slightly up, the narrow ion tail straight, the pale dust tail just
above it and gently curved, as on the README banner.

Run:  python3 scripts/gen_comet_mark.py   (needs Pillow)
"""
import math
import os
import random

from PIL import Image, ImageDraw, ImageFilter

W, H = 208, 110         # the bitmap box
HX, HY = 168, 66         # the head
AXIS = -168.0            # tail direction, degrees (0 = right, -90 = up)
SS = 6                   # supersampling for the bitmap

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def strands():
    """(kind, x0, y0, cx, cy, x1, y1, width, alpha): kind 0 dust, 1 ion."""
    rnd = random.Random(5)
    out = []
    # dust: a soft fan just above the axis, curved upward
    for _ in range(9):
        a = math.radians(AXIS + rnd.uniform(2.0, 10.0))
        L = rnd.uniform(130, 168)
        ex, ey = HX + math.cos(a) * L, HY + math.sin(a) * L
        px, py = math.sin(a), -math.cos(a)
        cx = HX + math.cos(a) * L * 0.5 - px * L * 0.06
        cy = HY + math.sin(a) * L * 0.5 - py * L * 0.06
        out.append((0, HX, HY, cx, cy, ex, ey, rnd.uniform(2.0, 5.0), rnd.uniform(0.35, 0.6)))
    # ion: narrow and straight along the axis
    for _ in range(6):
        a = math.radians(AXIS + rnd.uniform(-1.2, 1.2))
        L = rnd.uniform(150, 172)
        ex, ey = HX + math.cos(a) * L, HY + math.sin(a) * L
        cx, cy = (HX + ex) / 2, (HY + ey) / 2
        out.append((1, HX, HY, cx, cy, ex, ey, rnd.uniform(1.4, 3.0), rnd.uniform(0.55, 0.85)))
    return out


def bez(s, t):
    _, x0, y0, cx, cy, x1, y1, _, _ = s
    u = 1 - t
    return (u * u * x0 + 2 * u * t * cx + t * t * x1, u * u * y0 + 2 * u * t * cy + t * t * y1)


def render_bitmap(sts):
    img = Image.new("L", (W * SS, H * SS), 0)
    for s in sts:
        layer = Image.new("L", img.size, 0)
        d = ImageDraw.Draw(layer)
        n = 24
        for k in range(n):
            t0, t1 = k / n, (k + 1) / n
            tm = (t0 + t1) / 2
            w = max(1.0, s[7] * (1 - 0.75 * tm)) * SS
            a = s[8] * (1 - tm) ** 1.4
            p0, p1 = bez(s, t0), bez(s, t1)
            d.line([(p0[0] * SS, p0[1] * SS), (p1[0] * SS, p1[1] * SS)], fill=int(255 * a), width=int(w))
        layer = layer.filter(ImageFilter.GaussianBlur(SS * (1.2 if s[0] == 0 else 0.5)))
        img = Image.composite(Image.new("L", img.size, 255), img, layer.point(lambda v: v))  # lighten
    # head: coma glow, then the bright core
    glow = Image.new("L", img.size, 0)
    gd = ImageDraw.Draw(glow)
    for r, v in ((14, 70), (9, 150), (5.5, 255)):
        gd.ellipse([(HX - r) * SS, (HY - r) * SS, (HX + r) * SS, (HY + r) * SS], fill=v)
    glow = glow.filter(ImageFilter.GaussianBlur(SS * 2.2))
    img = Image.composite(Image.new("L", img.size, 255), img, glow)
    d = ImageDraw.Draw(img)
    r = 3.2
    d.ellipse([(HX - r) * SS, (HY - r) * SS, (HX + r) * SS, (HY + r) * SS], fill=255)
    return img.resize((W, H), Image.LANCZOS)


def write_bitmap(img):
    px = list(img.get_flattened_data()) if hasattr(img, 'get_flattened_data') else list(img.getdata())
    lines = []
    for i in range(0, len(px), 12):
        row = []
        for v in px[i:i + 12]:
            r5, g6, b5 = v >> 3, v >> 2, v >> 3
            row.append("0x%04X" % ((r5 << 11) | (g6 << 5) | b5))
        lines.append("  " + ",".join(row) + ",")
    path = os.path.join(ROOT, "src", "comet_mark_rgb.h")
    with open(path, "w") as f:
        f.write("// SPDX-License-Identifier: GPL-3.0-or-later\n")
        f.write("// Comet boot mark, anti-aliased RGB565 (%dx%d, white-on-black). Generated by\n" % (W, H))
        f.write("// scripts/gen_comet_mark.py from the same geometry as ui-touch/CometMarkGeom.h.\n")
        f.write("#pragma once\n#include <stdint.h>\n")
        f.write("#define COMET_MARK_W %d\n#define COMET_MARK_H %d\n" % (W, H))
        f.write("// One copy in the image: the pixels are defined only where COMET_MARK_DEFINE is set\n")
        f.write("// (ui-touch/UITask.cpp); everyone else sees the declaration.\n")
        f.write("extern const uint16_t COMET_MARK_RGB565[COMET_MARK_W * COMET_MARK_H];\n")
        f.write("#if defined(COMET_MARK_DEFINE)\n")
        f.write("const uint16_t COMET_MARK_RGB565[COMET_MARK_W * COMET_MARK_H] = {\n")
        f.write("\n".join(lines))
        f.write("\n};\n#endif\n")


def write_geom(sts):
    path = os.path.join(ROOT, "src", "ui-touch", "CometMarkGeom.h")
    with open(path, "w") as f:
        f.write("// SPDX-License-Identifier: GPL-3.0-or-later\n")
        f.write("// The Comet boot mark's geometry, in the 208 x 110 box of comet_mark_rgb.h.\n")
        f.write("// Generated by scripts/gen_comet_mark.py (edit that, not this).\n#pragma once\n#include <stdint.h>\n\n")
        f.write("struct CometStrand { uint8_t kind; int16_t x0, y0, cx, cy, x1, y1; uint8_t width_x10, alpha; };   // kind 0 dust, 1 ion\n")
        f.write("static const int16_t kCometHeadX = %d, kCometHeadY = %d;\n" % (HX, HY))
        f.write("static const CometStrand kCometStrands[] = {\n")
        for s in sts:
            f.write("  {%d, %d, %d, %d, %d, %d, %d, %d, %d},\n" % (
                s[0], round(s[1]), round(s[2]), round(s[3]), round(s[4]), round(s[5]), round(s[6]),
                round(s[7] * 10), round(s[8] * 255)))
        f.write("};\n")


if __name__ == "__main__":
    sts = strands()
    write_geom(sts)
    img = render_bitmap(sts)
    write_bitmap(img)
    img.resize((W * 4, H * 4), Image.NEAREST).save(os.path.join(os.environ.get("TMPDIR", "/tmp"), "comet_mark_preview.png"))
    print("wrote src/comet_mark_rgb.h and src/ui-touch/CometMarkGeom.h")
